r"""
captions_to_tex.py — convert paper/figures/captions.md (generated by make_figures.py) into
paper/figures/captions.tex, defining one macro per figure: \csuse{cap-F1}, \csuse{cap-F2}, ...

Captions are never hand-edited in LaTeX: numbers and SHA-256 prefixes flow from the figure
script through this converter unchanged. "Fig. Fn" / "(Table 3)" references in the captions are
turned into LaTeX cross-references so they match the paper's own numbering.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

UNI = {
    "≥": r"$\geq$", "≤": r"$\leq$", "−": r"$-$", "×": r"$\times$", "↔": r"$\leftrightarrow$",
    "→": r"$\rightarrow$", "≈": r"$\approx$", "±": r"$\pm$", "…": r"\ldots{}", "²": r"\textsuperscript{2}",
    "¹": r"\textsuperscript{1}", "–": "--", "—": "---",
}


def esc(s: str) -> str:
    s = s.replace("\\", r"\textbackslash{}")
    for a, b in (("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_"), ("$", r"\$")):
        s = s.replace(a, b)
    for a, b in UNI.items():
        s = s.replace(a, b)
    return s


def source_tex(src: str) -> str:
    parts = []
    for item in src.rstrip(".").split("; "):
        m = re.match(r"(.+?) \(SHA-256 ([0-9a-f]+)…\)", item)
        path, h = m.group(1), m.group(2)
        path_t = esc(path).replace("/", r"/\allowbreak{}")
        parts.append(r"\texttt{" + path_t + r"} (SHA-256 \texttt{" + h + r"}\ldots{})")
    return "; ".join(parts)


EDITIONS = {
    # lang: (input md, output tex, macro prefix, "Source" label)
    "en": ("captions.md", "captions.tex", "cap-", r"\emph{Source:}"),
    "th": ("captions_th.md", "captions_th.tex", "capth-", r"\emph{ที่มา:}"),
}


def protect_thai(root: Path, s: str) -> str:
    """Wrap words from tools/th_protected_words.txt in \\tw{...} (defined in main_th.tex)."""
    lst = root / "paper" / "tools" / "th_protected_words.txt"
    words = [w.strip() for w in lst.read_text(encoding="utf-8").splitlines()
             if w.strip() and not w.lstrip().startswith("#")]
    for w in sorted(words, key=len, reverse=True):
        s = re.sub(r"(?<!\\tw\{)" + re.escape(w), lambda m: "\\tw{" + m.group(0) + "}", s)
    return s


def convert(root: Path, lang: str) -> None:
    md_name, tex_name, prefix, src_label = EDITIONS[lang]
    md = (root / "paper" / "figures" / md_name).read_text(encoding="utf-8")
    out = [f"% generated by paper/tools/captions_to_tex.py from figures/{md_name} -- do not edit"]
    for block in md.split("\n**")[1:]:
        head, rest = block.split(".** ", 1)
        body, src = rest.split("\n*Source:* ", 1)
        key = head.split("_")[0]                      # F1, F2, ...
        body_t = esc(body.strip())
        body_t = re.sub(r"Fig\. (F\d)", lambda m: r"Figure~\ref{fig:" + m.group(1) + "}", body_t)
        body_t = re.sub(r"ภาพ (F\d)", lambda m: r"ภาพที่~\ref{fig:" + m.group(1) + "}", body_t)
        body_t = body_t.replace("(Table 3)", r"(Table~\ref{tab:ideas})")
        body_t = body_t.replace("(ตาราง 3)", r"(ตารางที่~\ref{tab:ideas})")
        if lang == "th":
            body_t = protect_thai(root, body_t)
        out.append("\\csdef{" + prefix + key + "}{" + body_t + " " + src_label + " " + source_tex(src.strip()) + ".}")
    (root / "paper" / "figures" / tex_name).write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"[{lang}] wrote {len(out) - 1} caption macros -> figures/{tex_name}")


def main(root: Path) -> None:
    for lang in EDITIONS:
        if (root / "paper" / "figures" / EDITIONS[lang][0]).exists():
            convert(root, lang)


if __name__ == "__main__":
    main(Path(sys.argv[1]).resolve())
